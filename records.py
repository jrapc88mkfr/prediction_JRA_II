def get_record(track, surface, distance):
    """
    コースレコード取得

    例:
        get_record("東京","芝",2400)
    """

    return RECORDS.get(
        (track, surface, distance)
    )


def time_to_seconds(time_str):
    """
    1:46.5 → 106.5
    """

    m, s = time_str.split(":")

    return int(m) * 60 + float(s)


def record_diff(track, surface, distance, race_time):
    """
    レコードとの差(秒)

    正ならレコードより遅い
    負ならレコード更新
    """

    record = get_record(track, surface, distance)

    if record is None:
        return None

    return (
        time_to_seconds(race_time)
        - time_to_seconds(record)
    )