import re

# =====================================
# レース情報抽出
# =====================================

def extract_race_info(text):

    text = str(text)

    track = None
    surface = None
    distance = None

    tracks = [
        "東京","中山","阪神","京都","中京",
        "新潟","札幌","函館","福島","小倉"
    ]

    for t in tracks:
        if t in text:
            track = t
            break

    m = re.search(r'(\d+)(芝|ダ)', text)

    if m:
        distance = int(m.group(1))
        surface = m.group(2)

    return track, surface, distance

