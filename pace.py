# =====================================
# 最初のコーナー位置取得
# =====================================
def get_first_position(text):

    m = re.search(r'kg\s+(\d+)\s+3F', str(text))

    if not m:
        return None

    pos = m.group(1)

    track, surface, distance = extract_race_info(text)

    corners = get_corner_count(
        track,
        distance,
        surface
    )

    # 直線競馬
    if corners == 0:
        return None

    # ----------------
    # 2コーナー戦
    # ----------------

    if corners == 2:

        if len(pos) == 2:
            return int(pos[0])

        if len(pos) == 4:
            return int(pos[:2])

    # ----------------
    # 3コーナー戦
    # ----------------

    elif corners == 3:

        if len(pos) == 3:
            return int(pos[0])

        if len(pos) == 6:
            return int(pos[:2])

    # ----------------
    # 4コーナー戦
    # ----------------

    else:

        if len(pos) == 4:

            # 1111 → 1
            if max(int(c) for c in pos) <= 9:
                return int(pos[0])

        if len(pos) == 8:

            return int(pos[:2])

    return None

# =====================================
# 脚質判定
# =====================================
def get_running_style(row):

    positions = []

    for col in ["前走","前々走","3走前"]:

        pos = get_first_position(row[col])

        if pos is not None:
            positions.append(pos)

    if not positions:
        return "不明"

    avg = sum(positions) / len(positions)

    if avg <= 3:
        return "逃"

    elif avg <= 7:
        return "先"

    elif avg <= 12:
        return "差"

    else:
        return "追"
    
